async page => {
  const FILE = globalThis.B1_FILE;
  const K = "b1VocabStories_v1";
  const out = [];
  const ok = (name, cond, extra) => out.push((cond ? "PASS " : "FAIL ") + name + (extra ? " | " + extra : ""));
  const errors = [];
  page.on("pageerror", e => errors.push(String(e)));
  const web = /^https?:/.test(FILE);
  const REAL = "Liebe Lena, vielen Dank für deine Einladung. Leider kann ich am Samstag nicht kommen, weil ich arbeiten muss. Hast du am Sonntag Zeit? Viele Grüße, Sam";
  const today = await page.evaluate(() => { const d = new Date(); return d.getFullYear() + "-" + ("0" + (d.getMonth() + 1)).slice(-2) + "-" + ("0" + d.getDate()).slice(-2); });
  const dmy = today.split("-").reverse().join(".");
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(FILE);
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  ok("with working storage there is no warning", !(await page.$("#storeWarn")));
  await page.click("#bToc");
  let t = await page.$eval("article", a => a.textContent);
  ok("the progress tools say there is no backup yet", /Noch nie gesichert/.test(t));
  ok(web ? "on the website they say new versions come by themselves" : "for the file they explain how to get a new version", web ? /kommt jede neue Version von selbst/.test(t) : /Neue Version bekommen\?/.test(t));
  await page.evaluate(() => { window.__dl = ""; HTMLAnchorElement.prototype.click = function () { if (this.download) window.__dl = this.download; }; });
  await page.click("#saveProg");
  const S = await page.evaluate(k => JSON.parse(localStorage.getItem(k) || "{}"), K);
  await page.click("#bDay");
  await page.click("#bToc");
  ok("after a backup, the date of the last backup shows", S.lastSave === today && (await page.$eval("article", a => a.textContent)).includes("Zuletzt gesichert: " + dmy) && /^b1-fortschritt-/.test(await page.evaluate(() => window.__dl)), S.lastSave);

  const broken = await page.context().newPage();
  const e2 = [];
  broken.on("pageerror", e => e2.push(String(e)));
  await broken.addInitScript(() => { const no = () => { throw new DOMException("blocked", "SecurityError"); }; Storage.prototype.setItem = no; Storage.prototype.getItem = no; Storage.prototype.removeItem = no; });
  await broken.goto(FILE);
  const w = await broken.$eval("#storeWarn", d => d.textContent).catch(() => "");
  ok("when the browser blocks storage, a warning shows and the page still works", /speichert gerade keinen Fortschritt/.test(w) && !!(await broken.$(".day .tasks")) && e2.length === 0, w.slice(0, 60) + " " + e2.join(" | "));
  await broken.click('.task[data-t="w"]').catch(() => {});
  ok("… and using it does not crash", e2.length === 0, e2.join(" | "));
  await broken.close();

  await page.goto(FILE);
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  const before = !!(await page.$("#hideWelcome"));
  const other = await page.context().newPage();
  await other.goto(FILE);
  await other.click("#hideWelcome");
  await page.bringToFront();
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await page.waitForFunction(() => !document.querySelector("#hideWelcome"), null, { timeout: 3000 }).catch(() => {});
  ok("a change in another tab shows here too when you come back to it, without a reload", before && !(await page.$("#hideWelcome")) && !!(await page.$(".day .tasks")));
  const raw = await page.evaluate(k => localStorage.getItem(k), K);
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  ok("coming back without a change does not touch the page", (await page.evaluate(k => localStorage.getItem(k), K)) === raw && !!(await page.$(".day .tasks")));
  await other.close();

  const p = await page.context().newPage();
  await p.addInitScript(() => { window.__persist = 0; if (window.StorageManager) StorageManager.prototype.persist = () => { window.__persist++; return Promise.resolve(true); }; });
  await p.goto(FILE);
  const built = await p.evaluate(() => JSON.parse(document.getElementById("data").textContent).hoeren.map(h => [h.id, h.items.length]));
  await p.evaluate(([k, built]) => { const S = { v: 2, welcomed: true, hres: {} }; built.forEach(([id, n]) => { S.hres[id] = { r: Array(n).fill(1), d: "2026-11-01" }; }); localStorage.setItem(k, JSON.stringify(S)); }, [K, built]);
  await p.goto(FILE + "#/schreiben");
  await p.reload();
  await p.fill("#mtext", REAL);
  await p.click("#mDone");
  const n1 = await p.evaluate(() => window.__persist);
  await p.click("#bDay");
  await p.click('.task[data-t="h"]');
  await p.click("#ldone");
  const n2 = await p.evaluate(() => window.__persist);
  ok(web ? "on a website, the first finished task asks the browser once to keep the data, the second does not ask again" : "for a file, it never asks the browser to keep the data", web ? n1 === 1 && n2 === 1 : n1 === 0 && n2 === 0, "asked " + n1 + " then " + n2);
  await p.close();
  ok("no page errors", errors.length === 0, errors.join(" | "));
  return out.join("\n");
}
