async page => {
  const FILE = globalThis.B1_FILE;
  const out = [];
  const ok = (name, cond, extra) => out.push((cond ? "PASS " : "FAIL ") + name + (extra ? " | " + extra : ""));
  const errors = [];
  page.on("pageerror", e => errors.push(String(e)));
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(FILE);
  await page.evaluate(() => localStorage.clear());
  await page.evaluate(() => { const v = {}; for (let i = 1; i <= 28; i++) v[String(i).padStart(2, "0")] = "l"; localStorage.setItem("b1VocabStories_v1", JSON.stringify({ ver: v })); });
  await page.reload();
  ok("the page opens on Heute", await page.evaluate(() => !!document.querySelector(".tasks") && document.getElementById("bDay").classList.contains("cur")));
  await page.click("#bToc");
  ok("contents lists 28 stories", (await page.$$eval(".toc li", e => e.length)) === 28);
  await page.click('.toc li[data-n="01"]');
  const counts = await page.evaluate(() => ({ w: document.querySelectorAll("article .w").length, b: document.querySelectorAll("article .b").length, n: document.querySelectorAll("article .n").length, p: document.querySelectorAll("article .p").length, c: document.querySelectorAll('article .b[data-f="c"]').length }));
  ok("story 01 has bold B1, plain list words, other words, names and compounds", counts.w > 60 && counts.b > 300 && counts.n > 10 && counts.p > 5 && counts.c > 2, JSON.stringify(counts));
  const beantr = await page.evaluate(() => { const el = [...document.querySelectorAll("article [data-id]")].find(x => /^beantrag/i.test(x.textContent)); return el ? el.className + " " + el.getAttribute("data-id") : "none"; });
  ok("beantragen in story 01 is bold now", /^w /.test(beantr), beantr);
  const tap = async (sel, nth) => {
    await page.keyboard.press("Escape");
    const el = page.locator(sel).nth(nth || 0);
    await el.scrollIntoViewIfNeeded();
    const b = await el.boundingBox();
    await page.mouse.click(b.x + Math.min(8, b.width / 2), b.y + b.height / 2);
    await page.waitForTimeout(150);
    return page.evaluate((wy) => { const c = document.getElementById("card"); const r = c.getBoundingClientRect(); return { vis: getComputedStyle(c).display === "block", text: c.innerText.replace(/\s+/g, " ").slice(0, 160), near: Math.abs(r.top - wy) < 60 || Math.abs(r.bottom - wy) < 90 }; }, b.y + b.height);
  };
  let r = await tap("article .w", 4);
  ok("tap a bold word: card shows B1 badge and meaning next to the word", r.vis && /B1/.test(r.text) && r.near, r.text);
  const bestIdx = await page.evaluate(() => [...document.querySelectorAll("article .b")].findIndex(x => /^bestehe|^bestand/i.test(x.textContent)));
  if (bestIdx >= 0) { r = await tap("article .b", bestIdx); ok("tap bestehen: card shows A2 and its meaning", r.vis && /A2/.test(r.text) && /pass/i.test(r.text), r.text); } else ok("bestehen found in story 01", false);
  r = await tap("article .b", 2);
  ok("tap a plain A1/A2 word: card opens", r.vis && /A1|A2/.test(r.text), r.text);
  const offIdx = await page.evaluate(() => { const D = JSON.parse(document.getElementById("data").textContent); return [...document.querySelectorAll("article .n")].findIndex(x => { const o = D.off && D.off[x.textContent]; return o && o.k === "word" && !o.id; }); });
  r = await tap("article .n", Math.max(0, offIdx));
  ok("tap a word that isn't on the list: card gives its meaning and says so", offIdx >= 0 && r.vis && /Nicht auf der B1-Wortliste/.test(r.text) && /nicht auf der Liste/.test(r.text), r.text);
  r = await tap("article .gw", 0);
  ok("tap a grammar word (article or pronoun): card explains it", r.vis && /Grammatikwort/.test(r.text), r.text);
  r = await tap("article .p", 0);
  ok("tap a name: card says Name", r.vis && /Name/.test(r.text), r.text);
  r = await tap('article .b[data-f="c"]', 0);
  ok("tap a compound: card shows its parts", r.vis && /Zusammengesetztes Wort/.test(r.text), r.text);
  await page.click("#cardX");
  ok("card closes", await page.evaluate(() => getComputedStyle(document.getElementById("card")).display === "none"));
  await page.selectOption("article .markSel", "en");
  ok("EN shows meanings inline for bold words", await page.evaluate(() => document.body.classList.contains("showen") && getComputedStyle(document.querySelector("article .w .gl")).display !== "none"));
  await page.selectOption("article .markSel", "b1");
  const qn = await page.evaluate(() => { const D = JSON.parse(document.getElementById("data").textContent); return Object.keys(D.quiz)[0] || null; });
  if (qn) {
    await page.click("#bToc");
    await page.click('.toc li[data-n="' + qn + '"]');
    const nq = await page.$$eval(".qq", e => e.length);
    ok("story " + qn + " ends with a 5-question quiz", nq === 5, String(nq));
    const ans = await page.evaluate(() => JSON.parse(document.getElementById("data").textContent));
    const Q = ans.quiz[qn];
    const wrong0 = [0, 1, 2].find(j => j !== Q[0].a);
    await page.click('.qq[data-k="0"] .opt[data-j="' + wrong0 + '"]');
    const early = await page.evaluate(() => ({ fb: document.querySelector('.qq[data-k="0"] .fb').innerText, sel: document.querySelectorAll('.qq[data-k="0"] .opt.picked').length, marks: document.querySelectorAll(".opt.yes, .opt.no").length, disabled: document.getElementById("qcheck").disabled, left: document.querySelector(".checkbar .left").textContent }));
    ok("picking an answer shows no right or wrong yet", early.fb === "" && early.sel === 1 && early.marks === 0, JSON.stringify(early));
    ok("check button stays off until every question is answered", early.disabled && /Noch 4 Fragen offen/.test(early.left), early.left);
    await page.click('.qq[data-k="0"] .opt[data-j="' + Q[0].a + '"]');
    const moved = await page.evaluate((a) => ({ sel: [...document.querySelectorAll('.qq[data-k="0"] .opt.picked')].map(b => +b.getAttribute("data-j")) }), Q[0].a);
    ok("you can change an answer before checking", moved.sel.length === 1 && moved.sel[0] === Q[0].a, JSON.stringify(moved));
    for (let k = 1; k < 4; k++) await page.click('.qq[data-k="' + k + '"] .opt[data-j="' + Q[k].a + '"]');
    const wrong4 = [0, 1, 2].find(j => j !== Q[4].a);
    await page.click('.qq[data-k="4"] .opt[data-j="' + wrong4 + '"]');
    const ready = await page.evaluate(() => ({ disabled: document.getElementById("qcheck").disabled, fb: [...document.querySelectorAll(".qq .fb")].map(f => f.innerText).join("") }));
    ok("after the last answer the check button turns on, still no feedback", !ready.disabled && ready.fb === "", JSON.stringify(ready).slice(0, 80));
    await page.click("#qcheck");
    const score = await page.$eval("#qscore", e => e.textContent);
    ok("score after checking", /4 von 5/.test(score), score);
    const fb4 = await page.$eval('.qq[data-k="4"] .fb', e => e.innerText);
    ok("a wrong answer shows the right one, the sentence and why", new RegExp("Falsch\\. Richtig ist " + "abc".charAt(Q[4].a) + "\\)").test(fb4) && fb4.length > 60, fb4.slice(0, 120));
    const fb0 = await page.$eval('.qq[data-k="0"] .fb', e => e.innerText);
    ok("a right answer says so", /^Richtig!/.test(fb0), fb0.slice(0, 40));
    const marks = await page.evaluate((w) => ({ no: document.querySelector('.qq[data-k="4"] .opt[data-j="' + w + '"]').classList.contains("no"), yes: document.querySelectorAll(".qq .opt.yes").length }), wrong4);
    ok("your wrong pick is marked, and every right answer is shown", marks.no && marks.yes === 5, JSON.stringify(marks));
    const optWord = await page.$$eval('.qq[data-k="1"] .opt .ot [class]', e => e.length);
    ok("after checking, words in the options are tappable", optWord > 0, String(optWord));
    await page.click('.qq[data-k="1"] .fb .show');
    await page.waitForTimeout(300);
    ok("'Stelle im Text zeigen' highlights the paragraph", await page.evaluate(() => !!document.querySelector("article p.flash")));
    await page.click("#bToc");
    const meta = await page.$eval('.toc li[data-n="' + qn + '"] .meta', e => e.textContent);
    ok("contents shows the quiz score", /Quiz 4\/5/.test(meta), meta);
  } else ok("a quiz exists", false);
  await page.click("#bIdx");
  await page.fill("#search", "bestehen");
  const hits = await page.$$eval("#idx li", e => e.slice(0, 3).map(x => x.textContent));
  ok("word index finds bestehen with level", hits.some(h => /bestehen/.test(h) && /A2/.test(h)), hits.join(" / ").slice(0, 150));
  await page.click("#bToc");
  await page.click('.toc li[data-n="01"]');
  await page.click("#mark");
  await page.click("#bToc");
  ok("read mark persists", (await page.textContent('.toc li[data-n="01"] .lchip')).includes("✓"));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.click('.toc li[data-n="05"]');
  r = await tap("article .w", 2);
  const box = await page.evaluate(() => { const r = document.getElementById("card").getBoundingClientRect(); return [Math.round(r.left), Math.round(r.right), innerWidth]; });
  ok("phone: card next to the word and inside the screen", r.vis && r.near && box[0] >= 0 && box[1] <= box[2], JSON.stringify(box));
  const audit = await page.evaluate(() => { const D = JSON.parse(document.getElementById("data").textContent); let miss = new Set(), bad = 0; D.stories.forEach(s => s.p.forEach(p => p.forEach(seg => { if (Array.isArray(seg) && seg[1]) seg[1].split(",").forEach(i => { const w = D.words[i]; if (!w) bad++; else if (!w.g) miss.add(i); }); }))); return { words: Object.keys(D.words).length, noGloss: [...miss].slice(0, 5), badRef: bad }; });
  ok("every tappable list word has a meaning", audit.noGloss.length === 0 && audit.badRef === 0, JSON.stringify(audit));
  ok("no page errors", errors.length === 0, errors.join("; ").slice(0, 300));
  return out.join("\n");
}
