async page => {
  const FILE = globalThis.B1_FILE;
  const out = [];
  const ok = (name, cond, extra) => out.push((cond ? "PASS " : "FAIL ") + name + (extra ? " | " + extra : ""));
  const errors = [];
  page.on("pageerror", e => errors.push(String(e)));
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(FILE);
  await page.evaluate(() => localStorage.clear());
  await page.evaluate(() => { const v = {}; for (let i = 1; i <= 28; i++) v[String(i).padStart(2, "0")] = "l"; localStorage.setItem("b1VocabStories_v1", JSON.stringify({ ver: v })); });
  await page.reload();
  await page.click("#bSyn");
  const sec = await page.evaluate(() => ({ groups: document.querySelectorAll(".syn details").length, items: document.querySelectorAll(".syn li").length, ex: document.querySelectorAll(".syn .ex").length, fam: document.querySelectorAll("table.fam tr").length, weil: !!document.getElementById("it-A-weil") }));
  ok("Satzbau section: groups, words, examples, families table", sec.groups === 9 && sec.items >= 100 && sec.ex > 80 && sec.fam === 15 && sec.weil, JSON.stringify(sec));
  const exw = await page.$eval("#it-A-weil", e => e.innerText.replace(/\s+/g, " ").slice(0, 200));
  ok("weil entry shows meaning, count and an example with its verb", /because/.test(exw) && /× in den Geschichten/.test(exw), exw);
  const hasVerbMark = await page.$$eval("#it-A-weil .ex .xv", e => e.length);
  ok("examples mark the verb", hasVerbMark > 0, String(hasVerbMark));
  await page.click("#it-A-weil .exgo");
  await page.waitForTimeout(400);
  const after = await page.evaluate(() => ({ story: !!document.querySelector("article h2") && document.querySelector("article h2").textContent, syn: document.body.classList.contains("showsyn"), flash: !!document.querySelector("article p.flash") }));
  ok("example link opens the story with Satzbau on and the paragraph flashed", after.story && after.syn && after.flash, JSON.stringify(after));
  const marks = await page.evaluate(() => ({ k: document.querySelectorAll("article .sk").length, v: document.querySelectorAll("article .sv").length }));
  ok("story has connector and verb marks", marks.k > 10 && marks.v > 5, JSON.stringify(marks));
  const kA = await page.$("article .sk-A");
  if (kA) {
    await kA.scrollIntoViewIfNeeded();
    const b = await kA.boundingBox();
    await page.mouse.click(b.x + b.width / 2, b.y + b.height / 2);
    await page.waitForTimeout(200);
    const c = await page.evaluate(() => ({ t: document.getElementById("card").innerText.replace(/\s+/g, " "), sel: document.querySelectorAll("article .sv.synsel").length }));
    ok("tap a type-A connector: card explains verb-to-end and highlights its verb", /Typ A/.test(c.t) && /Verb hier/.test(c.t) && c.sel >= 1, c.t.slice(0, 200) + " | verbs highlighted: " + c.sel);
    await page.click(".synmore");
    await page.waitForTimeout(300);
    ok("'Mehr dazu' opens the Satzbau section", await page.evaluate(() => !!document.querySelector(".syn")));
  } else ok("story has a type A connector", false);
  await page.click("#bToc");
  await page.click('.toc li[data-n="03"]');
  const v = await page.$("article .sv-C");
  if (v) {
    await v.scrollIntoViewIfNeeded();
    const b = await v.boundingBox();
    await page.keyboard.press("Escape");
    await page.mouse.click(b.x + b.width / 2, b.y + b.height / 2);
    await page.waitForTimeout(200);
    const c = await page.evaluate(() => document.getElementById("card").innerText.replace(/\s+/g, " "));
    ok("tap a flipped verb: card says which word moved it", /Dieses Verb steht hier wegen/.test(c), c.slice(0, 180));
  } else ok("story 03 has an inversion verb", false);
  await page.keyboard.press("Escape");
  await page.selectOption("article .markSel", "b1");
  ok("toggle turns Satzbau off", await page.evaluate(() => !document.body.classList.contains("showsyn")));
  await page.reload();
  ok("toggle state is saved", await page.evaluate(() => !document.body.classList.contains("showsyn")));
  await page.click("#bSyn");
  await page.click("#drillGo");
  const dq = await page.evaluate(() => ({ q: document.querySelectorAll(".drill .qq").length, gaps: document.querySelectorAll(".drill .gap").length, mails: document.querySelectorAll(".drill .mail").length }));
  ok("drill: 2 emails, 20 gaps, 20 questions", dq.q === 20 && dq.gaps === 20 && dq.mails === 2, JSON.stringify(dq));
  const D = await page.evaluate(() => JSON.parse(document.getElementById("data").textContent).syn.drill.texts);
  const g1 = D[0].gaps[0], wrong = [0, 1, 2].find(j => j !== g1.a);
  await page.click('.qq[data-t="0"][data-n="1"] .opt[data-j="' + wrong + '"]');
  const fb1 = await page.$eval('.qq[data-t="0"][data-n="1"] .fb', e => e.innerText);
  ok("drill: wrong answer is flagged with a word-order hint", /Nicht ganz/.test(fb1) && /verb/.test(fb1), fb1.slice(0, 90));
  await page.click('.qq[data-t="0"][data-n="1"] .opt[data-j="' + g1.a + '"]');
  const fill = await page.evaluate(() => ({ gap: document.getElementById("gap-1").textContent, cls: document.getElementById("gap-1").className, fb: document.querySelector('.qq[data-t="0"][data-n="1"] .fb').innerText }));
  ok("drill: right answer fills the gap and shows type + why", fill.gap === g1.o[g1.a] && /filled/.test(fill.cls) && /Typ A/.test(fill.fb) && /arbeite/.test(fill.fb), JSON.stringify(fill).slice(0, 200));
  for (let ti = 0; ti < 2; ti++) for (const g of D[ti].gaps) { if (ti === 0 && g.n === 1) continue; await page.click('.qq[data-t="' + ti + '"][data-n="' + g.n + '"] .opt[data-j="' + g.a + '"]'); }
  const sc = await page.evaluate(() => [document.getElementById("dscore-0").textContent, document.getElementById("dscore-1").textContent]);
  ok("drill: scores per email (first tries)", /9 von 10/.test(sc[0]) && /10 von 10/.test(sc[1]), sc.join(" | "));
  await page.click("#backSyn");
  const last = await page.evaluate(() => document.querySelector(".syn p .hint") ? document.querySelector(".syn p .hint").textContent : "");
  ok("Satzbau shows the last drill result", /9\/10/.test(last) && /10\/10/.test(last), last);
  ok("no page errors", errors.length === 0, errors.join("; ").slice(0, 300));
  return out.join("\n");
}
